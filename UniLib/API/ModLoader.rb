# ======================================================================================================================================== #
# ============================================================== PUBLIC API ============================================================== #
# ======================================================================================================================================== #

module UniLib

  def self.mod_staged?(id) = !STAGED_MODS[id].nil?

  def self.mod_loaded?(id) = !LOADED_MODS[id].nil?

  def self.lib_loaded?(id) = !LOADED_LIBRARIES[id].nil?

  def self.current_config(key) = MOD_CONFIGS[self.current_mod][key] rescue print(key)

  def self.get_config(id, key) = MOD_CONFIGS[id][key] rescue nil

  def self.current_cache_level = $unilib_current_cache_level

end