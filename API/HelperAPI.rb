module UniLib

  def self.get_form_number(holder, form)
    if form.is_a? String
      UniLib.include "Pokemon"
      tmp = FORM_MAP[holder][form + " Form"]
      tmp = FORM_MAP[holder][form + " Forme"] if tmp.nil?
      tmp = FORM_MAP[holder][form + " Rotom"] if tmp.nil?
      tmp = FORM_MAP[holder][form + " Mode"] if tmp.nil?
      tmp = FORM_MAP[holder][form] if tmp.nil?
      form = tmp
    end
    form
  end

end